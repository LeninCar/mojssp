"""Unit and integration tests for NSGA-II + Local Search (Phase 5)."""

from pathlib import Path
import sys
import unittest

# Add src to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from mojssp import (
    NSGA2LS,
    NSGA2LSResult,
    load_dzn,
    nsga2_ls,
    validate_schedule,
)


class TestNSGA2LS(unittest.TestCase):
    """Test suite for NSGA2LS execution, constraints, and reproducibility."""

    def setUp(self) -> None:
        toy_dzn = Path(__file__).resolve().parent.parent / "data" / "validation" / "toy_instance.dzn"
        self.instance = load_dzn(str(toy_dzn))

    def test_parameter_validations(self) -> None:
        """Test validation of constructor parameters."""
        with self.assertRaises(ValueError):
            NSGA2LS(population_size=2)
        with self.assertRaises(ValueError):
            NSGA2LS(generations=0)
        with self.assertRaises(ValueError):
            NSGA2LS(ls_non_f1_ratio=1.5)
        with self.assertRaises(ValueError):
            NSGA2LS(crossover_probability=1.2)

    def test_population_size_preserved_and_multiobjective_validity(self) -> None:
        """Test that final population matches population_size exactly and objectives are 3D."""
        pop_size = 12
        generations = 2
        algo = NSGA2LS(
            population_size=pop_size,
            generations=generations,
            max_ls_iterations=5,
            max_ls_neighbors=3,
            seed=42,
        )
        res = algo.run(self.instance)

        self.assertEqual(len(res.population), pop_size)
        self.assertEqual(len(res.population_objectives), pop_size)
        self.assertTrue(len(res.non_dominated_solutions) > 0)
        self.assertEqual(
            len(res.non_dominated_solutions), len(res.non_dominated_objectives)
        )

        for obj in res.non_dominated_objectives:
            self.assertGreater(obj.makespan, 0)
            self.assertGreaterEqual(obj.tardiness, 0)
            self.assertGreater(obj.energy, 0.0)

    def test_evaluations_counters(self) -> None:
        """Test that total_evaluations and ls_evaluations are accurately tracked."""
        algo = NSGA2LS(
            population_size=8,
            generations=2,
            max_ls_iterations=5,
            max_ls_neighbors=3,
            seed=101,
        )
        res = algo.run(self.instance)

        self.assertGreater(res.total_evaluations, 0)
        self.assertGreater(res.ls_evaluations, 0)
        self.assertLessEqual(res.ls_evaluations, res.total_evaluations)
        # Baseline evaluations from GA: pop_size * (1 + generations) = 8 * 3 = 24
        self.assertEqual(res.total_evaluations, 24 + res.ls_evaluations)

    def test_all_non_dominated_schedules_pass_validator(self) -> None:
        """Test that all non-dominated schedules generated by NSGA-II+LS are 100% valid."""
        algo = NSGA2LS(
            population_size=8,
            generations=2,
            max_ls_iterations=5,
            max_ls_neighbors=3,
            seed=55,
        )
        res = algo.run(self.instance)

        for sched in res.non_dominated_schedules:
            validate_schedule(self.instance, sched)

    def test_deterministic_reproducibility(self) -> None:
        """Test that identical seeds yield bitwise identical populations and evaluations."""
        res1 = nsga2_ls(
            self.instance,
            population_size=8,
            generations=2,
            max_ls_iterations=5,
            max_ls_neighbors=3,
            seed=777,
        )
        res2 = nsga2_ls(
            self.instance,
            population_size=8,
            generations=2,
            max_ls_iterations=5,
            max_ls_neighbors=3,
            seed=777,
        )

        self.assertEqual(res1.total_evaluations, res2.total_evaluations)
        self.assertEqual(res1.ls_evaluations, res2.ls_evaluations)
        self.assertEqual(
            [s.sequence for s in res1.non_dominated_solutions],
            [s.sequence for s in res2.non_dominated_solutions],
        )
        self.assertEqual(
            [(o.makespan, o.tardiness, o.energy) for o in res1.non_dominated_objectives],
            [(o.makespan, o.tardiness, o.energy) for o in res2.non_dominated_objectives],
        )


if __name__ == "__main__":
    unittest.main()

